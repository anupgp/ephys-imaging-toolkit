"""
stimulus_onset_detection.py
===========================

Finds WHEN the stimulus (e.g. glutamate uncaging) was delivered in one sweep
of an ``EphysRecording``. The traces-by-ISI view aligns every sweep to the
first stimulus, so this must be reliable.

Three ways to find the stimulus
-------------------------------
1. ``digital_output_bit="auto"`` (default)
   The Clampex protocol lists the TTL pulses sent on every digital output
   (decoded in ``axon_abf_protocol_decoder.py``). Several outputs are usually
   active (e.g. DO0 = camera/scope trigger, DO1 = uncaging laser), so the
   output is chosen automatically:
     * if the expected inter-stimulus interval (ISI, from the experiment
       sheet) is known: among the outputs whose mean pulse interval matches it
       (within 2 ms or 5 %), the one with the SHORTEST pulses (a gate held
       high for a 200 ms test step can coincidentally have the same interval
       as the 0.1 ms uncaging trigger, e.g. at ISI 800 ms),
     * if the expected ISI is 0 (single stimulus): an output with one pulse,
     * otherwise: the output with the most pulses; ties go to the output
       with the SHORTEST pulses (triggers are typically 0.1 ms long, while
       gating signals last hundreds of ms).
2. ``digital_output_bit=1`` (a number): always use that digital output.
3. ``stimulus_channel="IN7"``: use a RECORDED channel (a trigger or
   photodiode signal) and detect where it rises through a threshold. Use this
   on rigs where the stimulus is not generated by the Clampex protocol.

The result also says which source was used, so it can be shown in figures.
"""

from __future__ import annotations

import re
from dataclasses import dataclass, field

import numpy as np

from ..recording_data_containers.ephys_recording import EphysRecording


class StimulusDetectionError(ValueError):
    """Raised when no stimulus could be identified; the message explains why."""


@dataclass
class StimulusOnsets:
    """Stimulus onset times of one sweep and where they came from."""

    onsets_s: np.ndarray  # seconds from the start of the sweep, sorted
    source: str           # e.g. "digital output 1" or "recorded channel IN7 (> 250.0 mV)"
    # Recorded channels whose pulses coincide with these onsets (e.g. ["IN7"],
    # the light-pulse photodiode): independent confirmation of the choice.
    confirmed_by: list[str] = field(default_factory=list)

    @property
    def n_pulses(self) -> int:
        return len(self.onsets_s)

    @property
    def mean_interval_ms(self) -> float | None:
        """Mean time between consecutive onsets (None for a single pulse)."""
        if len(self.onsets_s) < 2:
            return None
        return float(np.diff(self.onsets_s).mean() * 1000)


def _interval_matches(measured_ms: float, expected_ms: float) -> bool:
    """Allow 2 ms or 5 % difference (protocol epochs add ~0.1 ms per pulse)."""
    return abs(measured_ms - expected_ms) <= max(2.0, 0.05 * expected_ms)


def _from_digital_outputs(
    recording: EphysRecording, sweep: int, digital_output_bit, expected_interval_ms: float | None
) -> StimulusOnsets:
    pulses = recording.stimulus_pulses
    pulses = pulses[pulses["sweep"] == sweep] if not pulses.empty else pulses
    if pulses.empty:
        raise StimulusDetectionError(
            f"{recording.file_name}, sweep {sweep}: the protocol has no digital output pulses. "
            "Use stimulus_channel='<recorded trigger channel>' instead."
        )

    by_output = {
        int(bit): group.sort_values("onset_s") for bit, group in pulses.groupby("digital_output_bit")
    }

    # --- a fixed output was requested ---------------------------------------------
    if digital_output_bit != "auto":
        bit = int(digital_output_bit)
        if bit not in by_output:
            raise StimulusDetectionError(
                f"{recording.file_name}, sweep {sweep}: no pulses on digital output {bit}; "
                f"outputs with pulses: {sorted(by_output)}."
            )
        return StimulusOnsets(by_output[bit]["onset_s"].to_numpy(), f"digital output {bit}")

    # --- automatic choice -----------------------------------------------------------
    def describe_outputs() -> str:
        parts = []
        for bit, group in by_output.items():
            onsets = group["onset_s"].to_numpy()
            interval = f", mean interval {np.diff(onsets).mean() * 1000:.1f} ms" if len(onsets) > 1 else ""
            parts.append(f"DO{bit}: {len(onsets)} pulse(s){interval}")
        return "; ".join(parts)

    if expected_interval_ms is not None and expected_interval_ms > 0:
        candidates = []
        for bit, group in by_output.items():
            onsets = group["onset_s"].to_numpy()
            if len(onsets) >= 2:
                interval_ms = float(np.diff(onsets).mean() * 1000)
                if _interval_matches(interval_ms, expected_interval_ms):
                    # Several outputs can match (e.g. ISI 800 ms: DO0 test-step gate
                    # 800.0 ms apart AND DO1 uncaging trigger 800.1 ms apart).
                    # Real stimulus triggers are SHORT pulses, so the output with the
                    # shortest longest-pulse wins; closeness to the ISI breaks ties.
                    longest_pulse_s = float(group["duration_s"].max())
                    candidates.append((longest_pulse_s, abs(interval_ms - expected_interval_ms), bit))
        if not candidates:
            raise StimulusDetectionError(
                f"{recording.file_name}, sweep {sweep}: no digital output has pulses "
                f"{expected_interval_ms:g} ms apart (sheet ISI). Found: {describe_outputs()}. "
                "Pass digital_output_bit=<n> or stimulus_channel=<channel> to choose explicitly."
            )
        best_bit = min(candidates)[2]
        return StimulusOnsets(by_output[best_bit]["onset_s"].to_numpy(), f"digital output {best_bit}")

    if expected_interval_ms == 0:
        single = [bit for bit, group in by_output.items() if len(group) == 1]
        if len(single) == 1:
            return StimulusOnsets(by_output[single[0]]["onset_s"].to_numpy(), f"digital output {single[0]}")

    # No usable expectation: most pulses, then shortest pulses.
    best_bit = min(by_output, key=lambda bit: (-len(by_output[bit]), by_output[bit]["duration_s"].mean(), bit))
    return StimulusOnsets(by_output[best_bit]["onset_s"].to_numpy(), f"digital output {best_bit}")


def _from_recorded_channel(
    recording: EphysRecording,
    sweep: int,
    stimulus_channel: str,
    threshold: float | None,
    min_separation_ms: float,
) -> StimulusOnsets:
    trace = recording.get_trace(stimulus_channel, sweep)
    unit = recording.channel_unit(stimulus_channel)
    # Baseline = median; peak = true maximum. (A trigger pulse can be only a few
    # samples long, e.g. 0.1 ms = 2 samples at 20 kHz, so percentiles would miss it.)
    low, high = float(np.median(trace)), float(trace.max())
    if threshold is None:
        # Without a given threshold: halfway between baseline and peak. A trigger
        # must clearly stand out from the noise, otherwise no pulse is reported.
        # Noise = spread of the bulk of the samples (5th-95th percentile), but at
        # least one ADC step: digitized signals are quantized, so a flat channel
        # may flicker by exactly one step (its median absolute deviation is 0).
        distinct_levels = np.unique(trace[: 200_000])
        adc_step = float(np.min(np.diff(distinct_levels))) if len(distinct_levels) > 1 else 0.0
        p5, p95 = np.percentile(trace, [5, 95])
        noise = max(float(p95 - p5), adc_step, 1e-12)
        if high - low < 5 * noise:
            raise StimulusDetectionError(
                f"{recording.file_name}, sweep {sweep}: channel {stimulus_channel} shows no clear "
                f"trigger signal (range {low:.3g}–{high:.3g} {unit}). Check the channel name "
                "or pass threshold=..."
            )
        threshold = low + 0.5 * (high - low)

    crossings = recording.find_threshold_crossings_s(stimulus_channel, sweep, threshold)
    # Ignore re-crossings caused by noise on the rising edge.
    kept: list[float] = []
    for time_s in crossings:
        if not kept or (time_s - kept[-1]) * 1000 >= min_separation_ms:
            kept.append(float(time_s))
    if not kept:
        raise StimulusDetectionError(
            f"{recording.file_name}, sweep {sweep}: channel {stimulus_channel} never crosses "
            f"{threshold:.3g} {unit}."
        )
    return StimulusOnsets(np.array(kept), f"recorded channel {stimulus_channel} (> {threshold:.3g} {unit})")


def find_stimulus_onsets(
    recording: EphysRecording,
    sweep: int,
    expected_interval_ms: float | None = None,
    digital_output_bit: int | str = "auto",
    stimulus_channel: str | None = None,
    threshold: float | None = None,
    min_separation_ms: float = 1.0,
) -> StimulusOnsets:
    """
    Stimulus onset times of one sweep (see module docstring for the rules).

    Parameters
    ----------
    recording, sweep : the recording and sweep index (0-based)
    expected_interval_ms : ISI from the experiment sheet; helps choose the output
    digital_output_bit : "auto" or a digital output number (ignored when
        ``stimulus_channel`` is given)
    stimulus_channel : name of a RECORDED trigger channel to use instead
    threshold : level for ``stimulus_channel`` (default: halfway baseline->peak)
    min_separation_ms : crossings closer than this are merged (debouncing)
    """
    if stimulus_channel:
        return _from_recorded_channel(recording, sweep, stimulus_channel, threshold, min_separation_ms)
    return _from_digital_outputs(recording, sweep, digital_output_bit, expected_interval_ms)


# =============================================================================
# Cross-checking with RECORDED channels, and identifying the stimulus
# =============================================================================
# The sheet's "chan_stim" can be wrong (e.g. 20260322: IN6 is flat, the light
# pulses are on IN7), and a protocol can drive several digital outputs (e.g.
# DO0 = gate for another device, DO1 = uncaging). So instead of trusting either,
# every recorded channel is scanned for brief pulses, and a digital output is
# "confirmed" when a recorded channel shows pulses at exactly its onsets.

# Pulses on a trigger channel are brief and rare: above threshold for less
# than this fraction of the sweep (a membrane-potential trace is not).
MAX_TRIGGER_DUTY_FRACTION = 0.05
# A recorded pulse and a digital pulse coincide if their onsets differ by at
# most this much (photodiode / cable latency is well below 1 ms).
ONSET_MATCH_TOLERANCE_S = 0.002


def trigger_like_channels(
    recording: EphysRecording, sweep: int, exclude: list[str] | tuple[str, ...] = ()
) -> list[StimulusOnsets]:
    """
    All recorded channels of a sweep that look like trigger / light-pulse
    signals: large, brief, sparse pulses. Channels in ``exclude`` (e.g. the
    response channel, whose stimulus artefacts can look like pulses) are skipped.
    """
    excluded = {name.replace(" ", "").lower() for name in exclude if name}
    found = []
    for channel in recording.channel_names:
        if channel.replace(" ", "").lower() in excluded:
            continue
        try:
            onsets = _from_recorded_channel(recording, sweep, channel, None, 1.0)
        except StimulusDetectionError:
            continue  # flat or noisy channel: not a trigger
        trace = recording.get_trace(channel, sweep)
        threshold = float(np.median(trace) + 0.5 * (trace.max() - np.median(trace)))
        if (trace >= threshold).mean() <= MAX_TRIGGER_DUTY_FRACTION:
            onsets.confirmed_by = [channel]
            found.append(onsets)
    return found


# Recorded channels known to carry the STIMULUS (light / stimulator) pulses on
# the rigs this package was written for:
#   Olympus 2P rig : IN7  = uncaging light pulses (photodiode)
#   Zeiss LSM rig  : trigger2 = stimulation train (trigger1 = microscope start)
# Used only to break ties: when two digital outputs are both confirmed by a
# recorded channel and look alike (same number and width of pulses), the one
# seen on one of these channels is the stimulus. Edit this list for a new rig.
LIGHT_PULSE_CHANNELS = ("IN7", "trigger2")


def _seen_on_light_channel(candidate: dict) -> bool:
    known = {name.lower() for name in LIGHT_PULSE_CHANNELS}
    return any(channel.replace(" ", "").lower() in known for channel in candidate["confirmed_by"])


def _onsets_coincide(first_s: np.ndarray, second_s: np.ndarray) -> bool:
    """Same number of pulses and every onset within ONSET_MATCH_TOLERANCE_S."""
    return len(first_s) == len(second_s) and bool(
        np.all(np.abs(np.sort(first_s) - np.sort(second_s)) <= ONSET_MATCH_TOLERANCE_S)
    )


def identify_stimulus(
    recording: EphysRecording,
    sweep: int,
    expected_interval_ms: float | None = None,
    response_channel: str | None = None,
) -> StimulusOnsets:
    """
    Decide which pulses are THE stimulus of a sweep, using every clue available.

    Rules, in order:
    1. Recorded channels are scanned for trigger / light pulses (see
       ``trigger_like_channels``; the response channel is excluded). A digital
       output whose onsets coincide with such a channel is "confirmed".
    2. If the expected ISI is known (from the sheet): among the outputs whose
       pulse interval matches it, confirmed ones win, then the shortest pulses.
    3. Otherwise: confirmed outputs win; among them (or among all outputs if
       none is confirmed) one seen on a known light-pulse channel
       (``LIGHT_PULSE_CHANNELS``, e.g. IN7), then the most pulses, then the
       shortest pulses. (2022-23 Olympus files: DO0 is seen on IN5 and DO1 on
       IN7 with identical pulses -> DO1.)
       (Zeiss rig: DO1 = one microscope-start pulse, DO2 = stimulation train
       -> DO2. Olympus rig: DO0 = 200 ms gate, DO1 = uncaging -> DO1.)
    4. No digital pulses at all: the recorded trigger channel with the most pulses.

    The returned ``source`` says what was used, e.g.
    "digital output 1, confirmed by IN7" or "digital output 1 (not confirmed by a recorded channel)".
    """
    if response_channel:
        excluded = [response_channel]
    else:
        # Response channel unknown (file not in the sheet): skip the amplifier
        # channels (Clampex names like ImLEFT, ImLeftP, VmLeftS), whose stimulus
        # artefacts can look like trigger pulses.
        excluded = [name for name in recording.channel_names if re.match(r"(im|vm|ic|vc)", name, re.IGNORECASE)]
    recorded_triggers = trigger_like_channels(recording, sweep, exclude=excluded)

    pulses = recording.stimulus_pulses
    pulses = pulses[pulses["sweep"] == sweep] if not pulses.empty else pulses
    if pulses.empty:
        if not recorded_triggers:
            raise StimulusDetectionError(
                f"{recording.file_name}, sweep {sweep}: no digital output pulses in the protocol and "
                "no recorded channel with trigger-like pulses."
            )
        best = max(recorded_triggers, key=lambda onsets: onsets.n_pulses)
        return best

    candidates = []
    for bit, group in pulses.groupby("digital_output_bit"):
        onsets_s = np.sort(group["onset_s"].to_numpy())
        confirmed_by = [t.confirmed_by[0] for t in recorded_triggers if _onsets_coincide(onsets_s, t.onsets_s)]
        interval_ms = float(np.diff(onsets_s).mean() * 1000) if len(onsets_s) > 1 else None
        candidates.append(
            {
                "bit": int(bit),
                "onsets_s": onsets_s,
                "confirmed_by": confirmed_by,
                "interval_ms": interval_ms,
                "longest_pulse_s": float(group["duration_s"].max()),
            }
        )

    if expected_interval_ms is not None and expected_interval_ms > 0:
        pool = [c for c in candidates if c["interval_ms"] is not None and _interval_matches(c["interval_ms"], expected_interval_ms)]
        if not pool:
            found = "; ".join(
                f"DO{c['bit']}: {len(c['onsets_s'])} pulse(s)"
                + (f", mean interval {c['interval_ms']:.1f} ms" if c["interval_ms"] else "")
                for c in candidates
            )
            raise StimulusDetectionError(
                f"{recording.file_name}, sweep {sweep}: no digital output has pulses "
                f"{expected_interval_ms:g} ms apart (sheet ISI). Found: {found}. "
                "Pass digital_output_bit=<n> or stimulus_channel=<channel> to choose explicitly."
            )
        best = min(pool, key=lambda c: (not c["confirmed_by"], not _seen_on_light_channel(c), c["longest_pulse_s"],
                                        abs(c["interval_ms"] - expected_interval_ms)))
    else:
        pool = [c for c in candidates if c["confirmed_by"]] or candidates
        best = min(pool, key=lambda c: (not _seen_on_light_channel(c), -len(c["onsets_s"]), c["longest_pulse_s"], c["bit"]))

    source = f"digital output {best['bit']}" + (
        f", confirmed by {'/'.join(best['confirmed_by'])}" if best["confirmed_by"] else " (not confirmed by a recorded channel)"
    )
    return StimulusOnsets(best["onsets_s"], source, confirmed_by=best["confirmed_by"])
